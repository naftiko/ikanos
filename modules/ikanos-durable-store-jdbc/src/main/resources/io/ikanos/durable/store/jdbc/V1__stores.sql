-- Schema version 1 of the durable stores: one table set per storage interface.
-- Applied once, in one transaction, when a store at version 0 opens.

CREATE TABLE executions (
    execution_id VARCHAR(255) PRIMARY KEY,
    spec_digest VARCHAR(255) NOT NULL,
    entry VARCHAR(1024),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    deadline TIMESTAMP(9) WITH TIME ZONE
);
CREATE INDEX executions_by_status ON executions (status, created_at);

CREATE TABLE execution_labels (
    execution_id VARCHAR(255) NOT NULL,
    label_key VARCHAR(255) NOT NULL,
    label_value VARCHAR(4096) NOT NULL,
    PRIMARY KEY (execution_id, label_key)
);
CREATE INDEX execution_labels_by_value ON execution_labels (label_key, label_value);

CREATE TABLE journal_heads (
    execution_id VARCHAR(255) PRIMARY KEY,
    last_sequence BIGINT NOT NULL,
    fencing_token BIGINT NOT NULL
);

CREATE TABLE journal (
    execution_id VARCHAR(255) NOT NULL,
    sequence BIGINT NOT NULL,
    kind VARCHAR(32) NOT NULL,
    path VARCHAR(4096),
    payload VARBINARY NOT NULL,
    PRIMARY KEY (execution_id, sequence)
);

CREATE TABLE work_queue (
    execution_id VARCHAR(255) PRIMARY KEY,
    due_at TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
CREATE INDEX work_queue_by_due ON work_queue (due_at);

CREATE TABLE leases (
    execution_id VARCHAR(255) PRIMARY KEY,
    owner VARCHAR(255) NOT NULL,
    fencing_token BIGINT NOT NULL,
    expires_at TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
CREATE SEQUENCE fencing_tokens START WITH 1;

CREATE TABLE inbox (
    execution_id VARCHAR(255) NOT NULL,
    path VARCHAR(4096) NOT NULL,
    delivered BIGINT NOT NULL,
    payload VARBINARY NOT NULL,
    acknowledged BOOLEAN NOT NULL,
    PRIMARY KEY (execution_id, path)
);
CREATE SEQUENCE inbox_order START WITH 1;

CREATE TABLE blobs (
    ref VARCHAR(512) PRIMARY KEY,
    execution_id VARCHAR(255) NOT NULL,
    payload BLOB NOT NULL
);
CREATE INDEX blobs_by_execution ON blobs (execution_id);

-- Reserved for MCP Events (Execution & Resolution Model 7.12): created empty, unused until then.
CREATE TABLE event_log (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id VARCHAR(255),
    event_type VARCHAR(255) NOT NULL,
    payload VARBINARY NOT NULL,
    recorded_at TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
